-- ============================================================
-- 007: дата отправки чек-листа по жалобе
--
-- Чек-лист по жалобе оценивают одним днём, а отправляют другим — сразу
-- дату отправки внести нельзя. В отчёты такая оценка должна попадать
-- по дате отправки, а обычная — по дате прослушки.
-- ============================================================
ALTER TABLE evaluations ADD COLUMN IF NOT EXISTS sent_at date;
CREATE INDEX IF NOT EXISTS evaluations_sent_idx ON evaluations (sent_at);
