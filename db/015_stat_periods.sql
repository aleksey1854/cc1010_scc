-- ============================================================
-- 015: период звонков у плана прослушки
--
-- Статистику принятых звонков иногда грузят за несколько дней сразу
-- (25–27.09 одной выгрузкой). План хранится под одной датой, а
-- «Прослушано» считало оценки только звонков ровно этой даты — и при
-- объединённых днях всегда показывало 0. Теперь у плана есть период:
-- прослушанным считается любой оценённый звонок из него.
--
-- Строки нет — период из одного дня, даты плана (как было раньше).
-- ============================================================
CREATE TABLE IF NOT EXISTS stat_periods (
  stat_date   date        PRIMARY KEY,
  period_from date        NOT NULL,
  period_to   date        NOT NULL,
  updated_by  text        NOT NULL DEFAULT '',
  updated_at  timestamptz NOT NULL DEFAULT now(),
  CHECK (period_from <= period_to)
);
