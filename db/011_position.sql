-- 011: должность рядом с ролью
--
-- Роль в системе — это права: кто что может нажать. А в жизни у людей
-- с одинаковыми правами разные должности: директор производственного
-- отдела (ДПП) и менеджер проектов Инвитро оба «руководители» для
-- системы, но в шапке должны отличаться.
--
-- Поэтому должность — отдельное поле, свободный текст: появится новая
-- — впишут, без правки кода и без раздачи новых прав.
-- ============================================================
