-- 012: проект ДЦ
--
-- Часть операторов — универсалы: работают и на ФСС, и на ДЦ. Чек-лист
-- у обоих проектов одинаковый, поэтому отличаем звонок отметкой прямо
-- в оценке. Так ДЦ можно посчитать отдельно, а на зарплату взять
-- среднее ФСС и ДЦ вместе.
--
-- В выгруженный бланк отметка не попадает — там для неё нет места.
-- ============================================================
ALTER TABLE evaluations ADD COLUMN IF NOT EXISTS dc boolean NOT NULL DEFAULT false;
CREATE INDEX IF NOT EXISTS evaluations_dc_idx ON evaluations (dc) WHERE dc;
