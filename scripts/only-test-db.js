// ============================================================
// scripts/only-test-db.js — предохранитель для опасных скриптов.
//
// С 28.09.2026 боевая база живая: состав, логины и пароли, которые
// Даниил раздал операторам. Скрипты, что сносят схему или заново
// заливают сотрудников, по ошибке запущенные на ней, стёрли бы всё это.
// Поэтому они работают только там, где явно стоит TEST_DB=1 — метка
// прописана в .env.test и больше нигде.
// ============================================================
module.exports = function onlyTestDb(name) {
  if (process.env.TEST_DB === '1') return;
  console.error(name + ': отказ — это не тестовая база (нет TEST_DB=1).\n' +
    'Скрипт стирает или переписывает сотрудников, на боевой базе он не запускается.\n' +
    'Тесты: ENV_FILE=.env.test bash test/run.sh');
  process.exit(1);
};
