const ALPHABET = 'abcdefghjkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789';  // без 0/O/1/l/I

function makeSeed(nOperators) {
  let s = 20260828;
  const rnd = () => (s = (s * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff;
  const pass = () => Array.from({ length: 10 }, () => ALPHABET[Math.floor(rnd() * ALPHABET.length)]).join('');

  const teams = ['ИНВ-1', 'ИНВ-2', 'ИНВ-3', 'ИНВ-УД1', 'ИНВ-УД2'];
  const people = [];
  const usedNames = new Set();
  const mk = (role, team) => {
    let full;
    do {
      full = FAM[Math.floor(rnd() * FAM.length)] + ' ' + NAM[Math.floor(rnd() * NAM.length)];
    } while (usedNames.has(full));
    usedNames.add(full);
    people.push({ full, team, role });
  };

  const n = nOperators || 60;
  for (let i = 0; i < n; i++) mk('operator', teams[i % teams.length]);
  teams.forEach(t => mk('rgo', t));
  for (let i = 0; i < 3; i++) mk('qc', 'СКК');
  mk('sqc', 'СКК');
  mk('srgo', 'Инвитро');
  mk('manager', 'Инвитро');
  mk('admin', 'АУП');

  // логины и хеши — тот же формат, что в бою
  const taken = {};
  const creds = [];
  const staffRows = [['ФИО', 'Группа', 'Роль', 'Пароль', 'Дата начала работы', 'Логин', 'Хеш пароля']];
  people.forEach((p, i) => {
    const login = core.suggestLogin(p.full, taken);
    taken[login] = true;
    const pw = pass();
    const hired = new Date(2023, 0, 1 + Math.floor(rnd() * 900));
    creds.push([p.full, p.team, p.role, login, pw]);
    staffRows.push([p.full, p.team, p.role, '', core.fmtDate(hired), login, core.hashPassword(pw)]);
  });

  // чек-лист в формате листа «Критерии ЧЛ»
  const critRows = [['ID', 'Блок', 'Пункт', 'Тип', 'Положительно', 'Сомнительно', 'Отрицательно',
                     'Не требуется', 'Правило', 'Активен']];
  CHECKLIST.forEach(([, bname, items]) => {
    items.forEach(it => {
      const [id, text, pos, dbt, neg, na, kind, rule] = it;
      critRows.push([id, bname, text, kind || 'score',
        pos === null ? '' : pos, dbt === null ? '' : dbt,
        neg === null ? '' : neg, na === null || na === undefined ? '' : na,
        rule || '', 'Да']);
    });
  });

  return {
    dump: {
      'Сотрудники': staffRows,
      'Выгрузка звонков': [['ID заявки', 'Дата создания', 'ФИО оператора', 'Группа', 'Дата звонка',
        'Время звонка', 'Номер телефона', 'Статус', 'Кто проверяет', 'Дата проверки', 'Оценка',
        'Комментарий QC', 'Комментарий/причина оператора', 'Тип звонка']],
      'Критерии ЧЛ': critRows,
      'Журнал оценок': [[]],
      'Тематики': [['Тематика', 'Подтематика']].concat(TOPICS),
      'Города': [['Город', 'Агломерация']].concat(CITIES),
      'Принятые звонки': [['Дата', 'ФИО оператора', 'Принято звонков']],
      'Настройки': [['Параметр', 'Значение', 'Комментарий'],
                    ['Процент выборки', 2, 'Сколько % принятых звонков слушать']]
    },
    creds
  };
}

if (require.main === module) {
  const arg = process.argv.slice(2).filter(a => a !== '--write');
  const { dump, creds } = makeSeed(Number(arg[0]) || 60);
  if (process.argv.includes('--write')) {
    const root = path.join(__dirname, '..');
    fs.writeFileSync(path.join(root, 'dump.json'), JSON.stringify(dump));
    fs.writeFileSync(path.join(root, 'seed-creds.json'), JSON.stringify(creds, null, 1));
    console.error('dump.json: сотрудников ' + creds.length + ', пунктов чек-листа ' +
                  (dump['Критерии ЧЛ'].length - 1));
    console.error('seed-creds.json: логины и пароли для демо');
  } else {
    process.stdout.write(JSON.stringify(dump));
  }
}

