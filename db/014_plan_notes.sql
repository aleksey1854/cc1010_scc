-- ============================================================
-- 014: примечание к плану прослушки
--
-- СКК иногда объединяют несколько дней в один план, и по самому плану
-- этого не понять — ни другим СКК, ни операторам. Примечание пишется
-- к дате плана и видно и в «Плане прослушки», и у оператора в кабинете.
-- ============================================================
CREATE TABLE IF NOT EXISTS plan_notes (
  stat_date  date        PRIMARY KEY,
  note       text        NOT NULL DEFAULT '',
  updated_by text        NOT NULL DEFAULT '',
  updated_at timestamptz NOT NULL DEFAULT now()
);
