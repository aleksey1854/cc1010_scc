-- 003: источник жалобы и замечания к выполненным пунктам
--
-- 1. В отчёте по жалобам ОБД сводит, сколько жалоб пришло от клиента,
--    а сколько от заказчика. Раньше это писали текстом в комментарий
--    к пункту «Признак жалобы в чек-листе» и считали руками.
-- 2. Комментарий разрешаем и к выполненному пункту: СКК пишет замечания
--    не только к ошибкам. Строка с «Положительно» без комментария
--    по-прежнему не хранится — это значение по умолчанию.
-- ============================================================
ALTER TABLE evaluations ADD COLUMN IF NOT EXISTS complaint_source text NOT NULL DEFAULT '';

ALTER TABLE evaluation_answers DROP CONSTRAINT IF EXISTS only_deviations;
ALTER TABLE evaluation_answers ADD CONSTRAINT only_deviations
  CHECK (value <> 'pos' OR comment <> '');
