-- ============================================================
-- 009: оператор узнаёт о новой оценке
--
-- Раньше оценка просто появлялась в списке — заметит или нет, дело
-- случая. Теперь у каждой оценки есть отметка «оператор её видел»:
-- пока она пустая, при входе висит плашка с новыми оценками, и в ней
-- отдельно подписано, если звонок был контрольным от заказчика.
--
-- Всю накопленную историю сразу помечаем просмотренной: иначе при
-- первом входе человеку высыпется полсотни «новых» оценок за месяц.
-- ============================================================
ALTER TABLE evaluations ADD COLUMN IF NOT EXISTS seen_at timestamptz;

UPDATE evaluations SET seen_at = now() WHERE seen_at IS NULL;

CREATE INDEX IF NOT EXISTS evaluations_unseen_idx
  ON evaluations (operator_id) WHERE seen_at IS NULL;
